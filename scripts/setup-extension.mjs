#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, "apps/web/.env.local");

/** Production Railway API — keep in sync with Vercel GIGSTER_API_URL */
const PRODUCTION_API_BASE = "https://gigsterbackend-production.up.railway.app";

const EXTENSION_APPS = ["extension-fiverr", "extension-upwork", "extension-freelancer"];

function parseEnv(text) {
  const out = {};
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i < 0) continue;
    const k = t.slice(0, i).trim();
    let v = t.slice(i + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    out[k] = v;
  }
  return out;
}

const production = process.argv.includes("--production");
let env = {};
if (existsSync(envPath)) {
  env = parseEnv(readFileSync(envPath, "utf8"));
}

const apiBase =
  process.env.GIGSTER_API_URL ||
  (production ? PRODUCTION_API_BASE : null) ||
  env.GIGSTER_API_URL ||
  "http://localhost:8000";

const configBody = `/** Generated by scripts/setup-extension.mjs */\nexport const config = {\n  apiBase: ${JSON.stringify(apiBase)},\n};\n`;

for (const app of EXTENSION_APPS) {
  const srcDir = join(root, "apps", app, "src");
  if (!existsSync(srcDir)) continue;
  mkdirSync(srcDir, { recursive: true });
  const outPath = join(srcDir, "config.local.js");
  writeFileSync(outPath, configBody, "utf8");
  console.log("Wrote", outPath, "→", apiBase);
}
